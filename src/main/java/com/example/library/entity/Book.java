package com.example.library.entity;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import lombok.ToString;

@Entity                      // this class is saved in the database
@Table(name = "books")       // table name
@Getter
@Setter
@NoArgsConstructor           // JPA needs a constructor without parameters
@ToString
public class Book {

    @Id                                                   // primary key
    @GeneratedValue(strategy = GenerationType.IDENTITY)   // 1, 2, 3... generated by the database
    private Long id;

    @Column(nullable = false, length = 100)
    private String title;

    @Column(nullable = false, length = 60)
    private String author;

    @Column(name = "published_year")   // "year" is a reserved word in SQL
    private int publishedYear;

    private boolean available = true;

    public Book(String title, String author, int publishedYear) {
        this.title = title;
        this.author = author;
        this.publishedYear = publishedYear;
    }
}
